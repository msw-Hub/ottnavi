-- V5: 사용자 영역(ERD C). users, user_setting, user_subscription, user_price_override, wishlist_item (Task 034)
-- 탈퇴(FR-07)하면 users 행 하나를 지워 이 영역과 D·E 영역의 사용자 행이 함께 사라진다(FK ON DELETE CASCADE, TECH T-1).
-- NULL 표기가 없는 컬럼은 NOT NULL이다(ERD 머리말).

-- 로그인 사용자. 테이블 이름은 예약어(user)를 피하려고 복수형이다
CREATE TABLE users (
	id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	email          VARCHAR(255) NOT NULL,
	name           VARCHAR(100) NOT NULL,                         -- 구글 표시 이름. 비어 오면 서비스가 이메일 앞부분으로 채운다
	role           VARCHAR(10)  NOT NULL DEFAULT 'USER',          -- USER / ADMIN
	oauth_provider VARCHAR(20)  NOT NULL,                         -- MVP는 GOOGLE만
	oauth_subject  VARCHAR(100) NOT NULL,                         -- 구글 계정의 고유 번호(sub)
	created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
	CONSTRAINT uk_users_email UNIQUE (email),
	CONSTRAINT uk_users_oauth UNIQUE (oauth_provider, oauth_subject),
	CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN')),
	CONSTRAINT ck_users_oauth_provider CHECK (oauth_provider IN ('GOOGLE'))
);

-- 계산 조건. 행이 있으면 온보딩을 마친 사용자이고, 행은 첫 설정 저장(PUT /me/settings)이 만든다(가입 때 만들지 않는다)
CREATE TABLE user_setting (
	user_id               BIGINT      PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,   -- 탈퇴 시 함께 삭제
	monthly_budget        INT         NOT NULL,
	monthly_watch_minutes INT         NOT NULL,
	watch_preset          VARCHAR(10) NOT NULL,                   -- LIGHT / NORMAL / HEAVY / CUSTOM
	notification_enabled  BOOLEAN     NOT NULL DEFAULT FALSE,     -- 알림은 기본 꺼짐(D6)
	created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
	CONSTRAINT ck_user_setting_budget CHECK (monthly_budget >= 0),
	CONSTRAINT ck_user_setting_minutes CHECK (monthly_watch_minutes >= 0),
	CONSTRAINT ck_user_setting_preset CHECK (watch_preset IN ('LIGHT', 'NORMAL', 'HEAVY', 'CUSTOM'))
);

-- 서비스별 이용 상태. 미구독은 행을 두지 않는다(API가 행 없는 서비스를 NOT_SUBSCRIBED로 채운다)
CREATE TABLE user_subscription (
	id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,             -- 탈퇴 시 함께 삭제
	ott_service_id BIGINT      NOT NULL REFERENCES ott_service (id),
	status         VARCHAR(20) NOT NULL,                          -- SUBSCRIBED / FREE / UNKNOWN
	product_id     BIGINT      REFERENCES subscription_product (id),                         -- MVP는 NULL. 계산 단계가 서비스의 판매 중 단품을 찾는다
	plan_name      VARCHAR(30),                                   -- 표시용 요금제 이름. SUBSCRIBED일 때만 값이 있다
	billing_day    INT,                                           -- 결제일 1~31. SUBSCRIBED일 때만 값이 있다. 비면 서비스가 1을 채운다(DB 기본값 없음, D5)
	created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
	CONSTRAINT uk_user_subscription_user_service UNIQUE (user_id, ott_service_id),
	CONSTRAINT ck_user_subscription_status CHECK (status IN ('SUBSCRIBED', 'FREE', 'UNKNOWN')),
	CONSTRAINT ck_user_subscription_billing_day CHECK (billing_day IS NULL OR billing_day BETWEEN 1 AND 31),
	CONSTRAINT ck_user_subscription_paid_only CHECK (status = 'SUBSCRIBED' OR (plan_name IS NULL AND billing_day IS NULL))
);

-- 관리자 가격을 바꾸지 않고 사용자별로 덮어쓰는 금액(FR-11)
CREATE TABLE user_price_override (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id       BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,              -- 탈퇴 시 함께 삭제
	product_id    BIGINT      NOT NULL REFERENCES subscription_product (id),
	monthly_price INT         NOT NULL,
	created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
	CONSTRAINT uk_user_price_override_user_product UNIQUE (user_id, product_id),
	CONSTRAINT ck_user_price_override_price CHECK (monthly_price >= 0)
);

-- 찜. 드라마는 시즌별 행으로 저장한다. watched_at이 있으면 계산에서 제외한다.
-- 사용자당 최대 20개(watched_at이 없는 행)는 DB 제약이 아니라 서비스 규칙이다(Task 056에서 동시 요청 직렬화)
CREATE TABLE wishlist_item (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id       BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,              -- 탈퇴 시 함께 삭제
	watch_unit_id BIGINT      NOT NULL REFERENCES watch_unit (id),
	priority      VARCHAR(10) NOT NULL,                           -- MUST / WANT / MAYBE
	watched_at    TIMESTAMPTZ,                                    -- 다 봤음 표시 시각
	created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
	CONSTRAINT uk_wishlist_item_user_unit UNIQUE (user_id, watch_unit_id),
	CONSTRAINT ck_wishlist_item_priority CHECK (priority IN ('MUST', 'WANT', 'MAYBE'))
);
