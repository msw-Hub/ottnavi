-- V9: 서비스별 인기 순위 일별 스냅샷 (Task 107)
-- TMDB discover(한국, 서비스 제공처 필터, 인기순) 상위 작품을 하루 한 번 받아 쌓는다. "최근 7일" 순위는 이 표의 인기도 평균으로 만든다.
-- 오래된 날짜는 인기 수집 Job이 지운다(기본 14일 보관). 같은 날 다시 실행하면 그 날짜·서비스·매체의 행을 지우고 다시 넣어 중복이 쌓이지 않는다.

CREATE TABLE popularity_snapshot (
	id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	snapshot_date  DATE          NOT NULL,                        -- 스냅샷 날짜(KST)
	ott_service_id BIGINT        NOT NULL REFERENCES ott_service (id),
	media_type     VARCHAR(10)   NOT NULL,                        -- MOVIE / TV
	tmdb_id        INT           NOT NULL,
	title          VARCHAR(300)  NOT NULL,                        -- 한국어 제목. 우리 title 표에 없는 작품도 순위에 보이도록 함께 저장한다
	poster_path    VARCHAR(200),
	release_date   DATE,                                          -- 영화 개봉일 / 드라마 첫 방영일. 모르면 NULL
	popularity     NUMERIC(12, 3) NOT NULL,                       -- TMDB 인기도(그날 값). 7일 평균의 재료
	created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
	updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
	-- 같은 날·서비스·매체에서 같은 작품이 두 번 들어가지 않게 한다. 선두 컬럼이 날짜라 "오래된 날짜 삭제"와 "날짜 범위 조회"에도 쓰인다
	CONSTRAINT uk_popularity_snapshot UNIQUE (snapshot_date, ott_service_id, media_type, tmdb_id),
	CONSTRAINT ck_popularity_snapshot_media_type CHECK (media_type IN ('MOVIE', 'TV'))
);
