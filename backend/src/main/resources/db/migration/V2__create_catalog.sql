-- V2: 작품·데이터 영역(ERD A). tmdb_provider(+시드), title, watch_unit, availability, availability_change, genre, title_genre, title_cast (Task 033)
-- 수집 배치만 쓰고 공개 API·계산 엔진이 읽는다. NULL 표기가 없는 컬럼은 NOT NULL이다(ERD 머리말).

-- TMDB 제공처와 우리 서비스의 매핑. provider_id는 TMDB 값을 그대로 PK로 쓴다
CREATE TABLE tmdb_provider (
	provider_id    INT          PRIMARY KEY,                      -- TMDB 값 그대로(8, 1796 등)
	tmdb_name      VARCHAR(100) NOT NULL,                         -- TMDB 원본 라벨. 판정에 쓰지 않는다
	logo_path      VARCHAR(200),
	mapping_state  VARCHAR(20)  NOT NULL DEFAULT 'UNMAPPED',      -- UNMAPPED / MAPPED / IGNORED
	ott_service_id BIGINT       REFERENCES ott_service (id),      -- MAPPED일 때만 값이 있다
	tier           VARCHAR(20)  NOT NULL DEFAULT 'STANDARD',      -- STANDARD / AD
	first_seen_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
	CONSTRAINT ck_tmdb_provider_state CHECK (mapping_state IN ('UNMAPPED', 'MAPPED', 'IGNORED')),
	CONSTRAINT ck_tmdb_provider_tier CHECK (tier IN ('STANDARD', 'AD')),
	CONSTRAINT ck_tmdb_provider_mapped CHECK ((mapping_state = 'MAPPED') = (ott_service_id IS NOT NULL))
);
CREATE INDEX idx_tmdb_provider_service ON tmdb_provider (ott_service_id);

-- 작품(영화·드라마 공통). TMDB ID는 영화와 드라마가 겹칠 수 있어 (media_type, tmdb_id)로 유일하게 한다
CREATE TABLE title (
	id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	media_type        VARCHAR(10)  NOT NULL,                      -- MOVIE / TV. API는 소문자 movie/tv(변환은 도메인 enum)
	tmdb_id           INT          NOT NULL,
	title             VARCHAR(300) NOT NULL,                      -- 한국어 제목(없으면 원제)
	original_title    VARCHAR(300),
	overview          TEXT,                                       -- 줄거리. 비어 있을 수 있다
	overview_lang     VARCHAR(5),                                 -- ko / en. 영어로 대체했는지 표시
	release_date      DATE,                                       -- 영화 개봉일 / 드라마 첫 방영일
	poster_path       VARCHAR(200),
	backdrop_path     VARCHAR(200),
	original_language VARCHAR(10),
	tv_status         VARCHAR(30),                                -- 드라마만(Returning Series, Ended 등)
	popularity        NUMERIC(10, 3),                             -- 엔티티는 BigDecimal로 매핑한다(Double이면 validate가 막을 수 있다)
	vote_average      NUMERIC(4, 2),
	refresh_tier      VARCHAR(10)  NOT NULL DEFAULT 'WEEKLY',     -- DAILY(찜에 있음) / WEEKLY(나머지 후보)
	fetched_at        TIMESTAMPTZ  NOT NULL,                      -- 마지막 수집 시각. 6개월 갱신 규칙 점검에 쓴다
	created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
	CONSTRAINT uk_title_media_tmdb UNIQUE (media_type, tmdb_id),
	CONSTRAINT ck_title_media_type CHECK (media_type IN ('MOVIE', 'TV')),
	CONSTRAINT ck_title_overview_lang CHECK (overview_lang IN ('ko', 'en')),
	CONSTRAINT ck_title_refresh_tier CHECK (refresh_tier IN ('DAILY', 'WEEKLY'))
);

-- 시청 단위(영화 1편 또는 시즌 1개). 찜·제공 상태·계산이 모두 이 테이블을 기준으로 한다
CREATE TABLE watch_unit (
	id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	title_id              BIGINT       NOT NULL REFERENCES title (id),
	unit_type             VARCHAR(10)  NOT NULL,                  -- MOVIE / SEASON
	season_number         INT,                                    -- 영화는 NULL. 시즌 0(스페셜)은 수집하지 않는다
	tmdb_season_id        INT,                                    -- 시즌만
	name                  VARCHAR(300),                           -- 시즌 표시용(영화는 title 값을 쓴다)
	poster_path           VARCHAR(200),
	air_date              DATE,
	episode_count         INT          NOT NULL DEFAULT 1,        -- 전체 회차 수(영화는 1)
	aired_episode_count   INT          NOT NULL DEFAULT 1,        -- 방영된 회차 수
	total_runtime_min     INT          NOT NULL,                  -- 방영된 회차 runtime 합 / 영화 runtime
	runtime_missing_count INT          NOT NULL DEFAULT 0,        -- runtime이 비어 기본값을 쓴 회차 수
	runtime_estimated     BOOLEAN      NOT NULL DEFAULT FALSE,    -- 추정값 포함 여부(화면 "추정" 표시)
	fetched_at            TIMESTAMPTZ  NOT NULL,
	created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
	-- 영화는 season_number가 NULL이라 일반 UNIQUE로는 영화 중복을 못 막는다. NULL끼리도 같은 값으로 본다
	CONSTRAINT uk_watch_unit_title_season UNIQUE NULLS NOT DISTINCT (title_id, season_number),
	CONSTRAINT ck_watch_unit_type CHECK (unit_type IN ('MOVIE', 'SEASON')),
	CONSTRAINT ck_watch_unit_season CHECK ((unit_type = 'SEASON') = (season_number IS NOT NULL)),
	CONSTRAINT ck_watch_unit_runtime CHECK (total_runtime_min >= 0)
);

-- 시청 단위 × 서비스 제공 상태. 서비스 단위로 집계해 저장한다
CREATE TABLE availability (
	id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	watch_unit_id  BIGINT       NOT NULL REFERENCES watch_unit (id),
	ott_service_id BIGINT       NOT NULL REFERENCES ott_service (id),
	status         VARCHAR(20)  NOT NULL,                         -- AVAILABLE / NOT_AVAILABLE / UNKNOWN
	unknown_reason VARCHAR(30),                                   -- UNKNOWN일 때만 값이 있다(NO_KR_DATA / STRUCTURAL_GAP)
	in_standard    BOOLEAN      NOT NULL DEFAULT FALSE,           -- STANDARD tier 제공처가 있었는지
	in_ad_tier     BOOLEAN      NOT NULL DEFAULT FALSE,           -- AD tier 제공처가 있었는지(광고형 판정)
	checked_at     TIMESTAMPTZ  NOT NULL,                         -- 마지막 확인 시각
	created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
	CONSTRAINT uk_availability_unit_service UNIQUE (watch_unit_id, ott_service_id),
	CONSTRAINT ck_availability_status CHECK (status IN ('AVAILABLE', 'NOT_AVAILABLE', 'UNKNOWN')),
	CONSTRAINT ck_availability_reason CHECK (unknown_reason IN ('NO_KR_DATA', 'STRUCTURAL_GAP')),
	CONSTRAINT ck_availability_unknown_reason CHECK ((status = 'UNKNOWN') = (unknown_reason IS NOT NULL))
);

-- 제공 상태 변경 이력. 재계산·변경 알림의 입력이고 수집이 계속 쌓는 가장 빨리 커지는 테이블이다
CREATE TABLE availability_change (
	id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	watch_unit_id    BIGINT       NOT NULL REFERENCES watch_unit (id),
	ott_service_id   BIGINT       NOT NULL REFERENCES ott_service (id),
	before_status    VARCHAR(20),                                 -- 신규는 NULL
	after_status     VARCHAR(20)  NOT NULL,
	job_execution_id BIGINT,                                      -- Spring Batch 실행 ID(FK 없이 참조값만). 배치 밖(단건 수집)이면 NULL
	changed_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
	CONSTRAINT ck_availability_change_before CHECK (before_status IN ('AVAILABLE', 'NOT_AVAILABLE', 'UNKNOWN')),
	CONSTRAINT ck_availability_change_after CHECK (after_status IN ('AVAILABLE', 'NOT_AVAILABLE', 'UNKNOWN'))
);
-- 실행별 "바뀐 작품" 조회와 실행 이력의 변경 건수 집계가 이 값으로 거른다(ERD 참조 컬럼 인덱스)
CREATE INDEX idx_availability_change_job ON availability_change (job_execution_id);

-- 장르(TMDB 장르 ID를 그대로 PK로 쓴다. 애니메이션은 16)
CREATE TABLE genre (
	id         INT          PRIMARY KEY,
	name       VARCHAR(50)  NOT NULL,
	created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE title_genre (
	title_id   BIGINT      NOT NULL REFERENCES title (id),
	genre_id   INT         NOT NULL REFERENCES genre (id),
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	PRIMARY KEY (title_id, genre_id)
);
-- 장르로 작품을 찾을 때(고도화 후보)를 위한 인덱스는 지금 만들지 않는다. PK의 선두는 title_id다

-- 출연진(상위 10명만 저장). 인물 테이블은 두지 않는다
CREATE TABLE title_cast (
	id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	title_id       BIGINT       NOT NULL REFERENCES title (id),
	cast_order     INT          NOT NULL,
	person_tmdb_id INT          NOT NULL,
	name           VARCHAR(200) NOT NULL,
	character_name VARCHAR(300),                                  -- 계약 CastMember.character가 nullable이다
	profile_path   VARCHAR(200),
	created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
	CONSTRAINT uk_title_cast_title_order UNIQUE (title_id, cast_order),
	CONSTRAINT ck_title_cast_order CHECK (cast_order >= 0)
);

