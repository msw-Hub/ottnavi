-- V6: 플랜 영역(ERD D). plan, plan_month, plan_month_product, plan_item, plan_assignment, calc_run (Task 034)
-- 계산 결과는 그 시점의 가격·조건을 복사한 스냅샷이다. DRAFT를 지우거나 사용자가 탈퇴하면 하위 행이 FK CASCADE로 함께 사라진다.
-- JPA는 cascade 삭제를 쓰지 않는다. plan 삭제는 벌크 JPQL로 하고 하위 행은 DB가 지운다(TECH T-1).

CREATE TABLE plan (
	id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id               BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,     -- 탈퇴 시 함께 삭제
	previous_plan_id      BIGINT       REFERENCES plan (id) ON DELETE SET NULL,              -- 재계산 전 플랜. 지워져도 이 플랜은 남긴다(자기참조 삭제 순서 문제 방지)
	status                VARCHAR(10)  NOT NULL,                  -- DRAFT / ACTIVE / ARCHIVED
	plan_type             VARCHAR(15)  NOT NULL,                  -- RECOMMENDED / SAVER / SIMPLE
	start_month           DATE         NOT NULL,                  -- 첫 달의 1일. API에서는 YYYY-MM
	monthly_budget        INT          NOT NULL,                  -- 계산 당시 값의 스냅샷
	monthly_watch_minutes INT          NOT NULL,                  -- 계산 당시 값의 스냅샷
	algorithm             VARCHAR(10)  NOT NULL,                  -- EXACT / GREEDY
	must_total            INT          NOT NULL,
	must_completed        INT          NOT NULL,
	score                 INT          NOT NULL,
	total_cost            INT          NOT NULL,
	all_subscribe_cost    INT          NOT NULL,                  -- 절감액 = all_subscribe_cost - total_cost (절감액은 저장하지 않는다)
	data_as_of            TIMESTAMPTZ  NOT NULL,                  -- 계산에 쓴 마지막 완료 수집 시각(D2)
	activated_at          TIMESTAMPTZ,                            -- ACTIVE로 저장된 시각. DRAFT만 NULL(D1)
	change_summary        TEXT,                                   -- 재계산 변경 요약. MVP는 NULL, 형식은 Task 069에서 정한다
	created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
	CONSTRAINT ck_plan_status CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED')),
	CONSTRAINT ck_plan_type CHECK (plan_type IN ('RECOMMENDED', 'SAVER', 'SIMPLE')),
	CONSTRAINT ck_plan_algorithm CHECK (algorithm IN ('EXACT', 'GREEDY')),
	CONSTRAINT ck_plan_activated CHECK ((status = 'DRAFT') = (activated_at IS NULL)),
	CONSTRAINT ck_plan_must CHECK (must_completed <= must_total),
	CONSTRAINT ck_plan_start_month CHECK (EXTRACT(DAY FROM start_month) = 1),
	CONSTRAINT ck_plan_amounts CHECK (monthly_budget >= 0 AND monthly_watch_minutes >= 0 AND must_total >= 0
		AND must_completed >= 0 AND score >= 0 AND total_cost >= 0 AND all_subscribe_cost >= 0)
);
-- 사용자당 ACTIVE는 하나, DRAFT는 유형마다 하나. 부분 유니크 인덱스(WHERE 조건에 맞는 행끼리만 유일해야 한다)
CREATE UNIQUE INDEX uk_plan_active ON plan (user_id) WHERE status = 'ACTIVE';
CREATE UNIQUE INDEX uk_plan_draft_type ON plan (user_id, plan_type) WHERE status = 'DRAFT';
-- 위 두 인덱스는 ARCHIVED 행을 덮지 못하므로 사용자 삭제(탈퇴)용 인덱스를 따로 둔다
CREATE INDEX idx_plan_user ON plan (user_id);
CREATE INDEX idx_plan_previous ON plan (previous_plan_id);

CREATE TABLE plan_month (
	id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	plan_id     BIGINT      NOT NULL REFERENCES plan (id) ON DELETE CASCADE,                 -- 플랜 삭제 시 함께 삭제
	month_index INT         NOT NULL,                             -- 0은 확정(이번 달), 1·2는 예상
	month       DATE        NOT NULL,                             -- 그 달의 1일. API에서는 YYYY-MM
	confirmed   BOOLEAN     NOT NULL,                             -- month_index가 0이면 true(파생 값이라 CHECK로 묶는다)
	cost        INT         NOT NULL,
	CONSTRAINT uk_plan_month_plan_index UNIQUE (plan_id, month_index),
	CONSTRAINT ck_plan_month_index CHECK (month_index >= 0),
	CONSTRAINT ck_plan_month_confirmed CHECK (confirmed = (month_index = 0)),
	CONSTRAINT ck_plan_month_first_day CHECK (EXTRACT(DAY FROM month) = 1),
	CONSTRAINT ck_plan_month_cost CHECK (cost >= 0)
);

-- 그 달에 구독할 상품. 가격 스냅샷이라 이후 가격이 바뀌어도 변하지 않는다
CREATE TABLE plan_month_product (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	plan_month_id BIGINT      NOT NULL REFERENCES plan_month (id) ON DELETE CASCADE,         -- 달 삭제 시 함께 삭제
	product_id    BIGINT      NOT NULL REFERENCES subscription_product (id),
	applied_price INT         NOT NULL,
	price_source  VARCHAR(20) NOT NULL,                           -- ADMIN / USER_OVERRIDE / ALREADY_PAID / FREE
	CONSTRAINT uk_plan_month_product UNIQUE (plan_month_id, product_id),                     -- plan_month_id 조회도 이 인덱스가 맡는다
	CONSTRAINT ck_plan_month_product_price CHECK (applied_price >= 0),
	CONSTRAINT ck_plan_month_product_source CHECK (price_source IN ('ADMIN', 'USER_OVERRIDE', 'ALREADY_PAID', 'FREE'))
);

-- 찜 단위(작품 또는 시즌) 결과. "남은 작품과 이유"(FR-12)의 원천
CREATE TABLE plan_item (
	id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	plan_id               BIGINT      NOT NULL REFERENCES plan (id) ON DELETE CASCADE,       -- 플랜 삭제 시 함께 삭제
	watch_unit_id         BIGINT      NOT NULL REFERENCES watch_unit (id),
	priority              VARCHAR(10) NOT NULL,                   -- MUST / WANT / MAYBE (계산 당시 스냅샷)
	outcome               VARCHAR(15) NOT NULL,                   -- SCHEDULED / UNSCHEDULED
	reason                VARCHAR(15),                            -- UNSCHEDULED일 때만: NO_PROVIDER / UNKNOWN / BUDGET / TIME
	completed_month_index INT,                                    -- 시청을 끝내는 달(month_index). UNSCHEDULED면 NULL
	CONSTRAINT uk_plan_item_plan_unit UNIQUE (plan_id, watch_unit_id),
	CONSTRAINT ck_plan_item_priority CHECK (priority IN ('MUST', 'WANT', 'MAYBE')),
	CONSTRAINT ck_plan_item_outcome CHECK (outcome IN ('SCHEDULED', 'UNSCHEDULED')),
	CONSTRAINT ck_plan_item_reason CHECK ((outcome = 'UNSCHEDULED') = (reason IS NOT NULL)),
	CONSTRAINT ck_plan_item_reason_value CHECK (reason IS NULL OR reason IN ('NO_PROVIDER', 'UNKNOWN', 'BUDGET', 'TIME')),
	CONSTRAINT ck_plan_item_completed CHECK (completed_month_index IS NULL
		OR (outcome = 'SCHEDULED' AND completed_month_index >= 0))
);

-- 월별 시청 배정. 긴 시즌은 연속된 달에 걸쳐 여러 행으로 나뉘고 한 달에 한 조각이다
CREATE TABLE plan_assignment (
	id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	plan_item_id   BIGINT NOT NULL REFERENCES plan_item (id) ON DELETE CASCADE,              -- 항목 삭제 시 함께 삭제
	plan_month_id  BIGINT NOT NULL REFERENCES plan_month (id) ON DELETE CASCADE,             -- 달 삭제 시 함께 삭제(두 경로 모두 CASCADE)
	ott_service_id BIGINT NOT NULL REFERENCES ott_service (id),
	minutes        INT    NOT NULL,
	CONSTRAINT uk_plan_assignment_item_month UNIQUE (plan_item_id, plan_month_id),
	CONSTRAINT ck_plan_assignment_minutes CHECK (minutes > 0)
);
CREATE INDEX idx_plan_assignment_month ON plan_assignment (plan_month_id);

-- 완전탐색·그리디 비교 기록(FR-13). 플랜이 지워져도 통계로 남기고 plan_id만 NULL로 바꾼다
CREATE TABLE calc_run (
	id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	plan_id         BIGINT      REFERENCES plan (id) ON DELETE SET NULL,
	input_hash      CHAR(64)    NOT NULL,                         -- 정규화한 입력의 SHA-256(16진수 64자)
	plan_type       VARCHAR(15) NOT NULL,
	algorithm       VARCHAR(10) NOT NULL,
	must_completed  INT         NOT NULL,
	score           INT         NOT NULL,
	total_cost      INT         NOT NULL,
	candidate_count INT         NOT NULL,
	elapsed_ms      BIGINT      NOT NULL,
	created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
	CONSTRAINT ck_calc_run_type CHECK (plan_type IN ('RECOMMENDED', 'SAVER', 'SIMPLE')),
	CONSTRAINT ck_calc_run_algorithm CHECK (algorithm IN ('EXACT', 'GREEDY')),
	CONSTRAINT ck_calc_run_numbers CHECK (must_completed >= 0 AND score >= 0 AND total_cost >= 0
		AND candidate_count >= 0 AND elapsed_ms >= 0)
);
CREATE INDEX idx_calc_run_plan ON calc_run (plan_id);
