-- V3: 상품·요금 영역(ERD B). subscription_product, product_component, product_price (Task 033)
-- 요금제와 번들을 "구독 상품" 하나로 통일한다. 단품은 구성 서비스가 1개, 번들은 여러 개다.
-- 가격 시드는 넣지 않는다. 가격표는 관리자 화면(Task 061)에서 입력한다.

CREATE TABLE subscription_product (
	id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name         VARCHAR(100) NOT NULL,                           -- 예: 넷플릭스 스탠다드. 계약 name은 최대 100자
	product_type VARCHAR(10)  NOT NULL,                           -- SINGLE / BUNDLE
	active       BOOLEAN      NOT NULL DEFAULT TRUE,              -- false면 판매 종료. 삭제하지 않는다. API에서는 isActive
	created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
	CONSTRAINT ck_subscription_product_type CHECK (product_type IN ('SINGLE', 'BUNDLE'))
);

-- 상품에 포함된 서비스와 tier. MVP는 STANDARD 단품만 다룬다(AD tier와 번들은 2단계)
CREATE TABLE product_component (
	product_id     BIGINT      NOT NULL REFERENCES subscription_product (id),
	ott_service_id BIGINT      NOT NULL REFERENCES ott_service (id),
	tier           VARCHAR(20) NOT NULL DEFAULT 'STANDARD',       -- STANDARD / AD
	created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
	PRIMARY KEY (product_id, ott_service_id),
	CONSTRAINT ck_product_component_tier CHECK (tier IN ('STANDARD', 'AD'))
);
-- PK의 선두가 product_id라 서비스 쪽 조회는 따로 인덱스가 필요하다
CREATE INDEX idx_product_component_service ON product_component (ott_service_id);

-- 월 구독요금 이력. 종료일은 저장하지 않는다: 다음 줄 시작일의 전날까지 적용되고 마지막 줄은 계속 적용된다
CREATE TABLE product_price (
	id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	product_id       BIGINT       NOT NULL REFERENCES subscription_product (id),
	monthly_price    INT          NOT NULL,                       -- 원 단위 정수
	effective_from   DATE         NOT NULL,                       -- 적용 시작일(한국 날짜)
	last_verified_at TIMESTAMPTZ  NOT NULL,                       -- 관리자가 마지막으로 확인한 일시. 기본값을 두지 않는다
	created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
	CONSTRAINT uk_product_price_product_from UNIQUE (product_id, effective_from),
	CONSTRAINT ck_product_price_monthly CHECK (monthly_price >= 0)
);
