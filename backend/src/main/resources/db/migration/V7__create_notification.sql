-- 보낼 메일을 먼저 이 표에 적고(outbox) 별도 작업이 발송한다. 발송 이력 조회(FR-16)도 이 표를 쓴다
CREATE TABLE notification_outbox (
	id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id         BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,           -- 탈퇴 시 함께 삭제
	type            VARCHAR(20)  NOT NULL,                        -- SUBSCRIBE_GUIDE / MONTHLY / PLAN_CHANGE
	dedupe_key      VARCHAR(100) NOT NULL,                        -- 중복 생성 방지. 예: MONTHLY:{userId}:2026-11
	payload         JSONB        NOT NULL,                        -- 메일 본문을 만들 재료
	status          VARCHAR(10)  NOT NULL DEFAULT 'PENDING',      -- PENDING / SENT / FAILED
	attempt_count   INT          NOT NULL DEFAULT 0,
	next_attempt_at TIMESTAMPTZ  NOT NULL DEFAULT now(),          -- 이 시각 이후에 발송을 시도한다
	sent_at         TIMESTAMPTZ,
	last_error      TEXT,
	created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
	CONSTRAINT uk_notification_outbox_dedupe UNIQUE (dedupe_key),
	CONSTRAINT ck_notification_outbox_type CHECK (type IN ('SUBSCRIBE_GUIDE', 'MONTHLY', 'PLAN_CHANGE')),
	CONSTRAINT ck_notification_outbox_status CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
	CONSTRAINT ck_notification_outbox_attempt CHECK (attempt_count >= 0)
);
CREATE INDEX idx_notification_outbox_due ON notification_outbox (status, next_attempt_at);   -- 발송 대상 조회
CREATE INDEX idx_notification_outbox_user ON notification_outbox (user_id);                  -- 탈퇴 삭제용

-- @Scheduled 작업의 중복 실행을 막는 ShedLock 락 표. 구조는 ShedLock 공식 PostgreSQL 스크립트 그대로이며 이름·타입을 바꾸지 않는다
CREATE TABLE shedlock (
	name       VARCHAR(64)  NOT NULL,
	lock_until TIMESTAMP    NOT NULL,
	locked_at  TIMESTAMP    NOT NULL,
	locked_by  VARCHAR(255) NOT NULL,
	PRIMARY KEY (name)
);
